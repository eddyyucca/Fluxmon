<p>Everyone who uses Fluxmon has their own account. A <strong>role</strong> decides what the account can open, and an account can also be limited to certain routers. Admins manage accounts in <em>Settings → Accounts</em>.</p>

<h2>Roles</h2>
<table>
    <thead><tr><th>Role</th><th>Meant for</th><th>Can do</th></tr></thead>
    <tbody>
        <tr><td><strong>Admin</strong></td><td>Owner, IT manager</td><td>Everything: routers, settings, accounts, backups, audit log.</td></tr>
        <tr><td><strong>Technician</strong></td><td>Network staff</td><td>Monitoring, hotspot users and profiles, vouchers, reports, backups, alerts and checks, audit log. Cannot add routers or manage accounts and settings.</td></tr>
        <tr><td><strong>Cashier</strong></td><td>Counter staff</td><td>Sell vouchers, manage hotspot users, see reports and basic monitoring. Cannot edit profiles, see backups or open settings.</td></tr>
        <tr><td><strong>Viewer</strong></td><td>Owner who only watches</td><td>Read-only: dashboard, monitoring, users and reports. Cannot change anything.</td></tr>
    </tbody>
</table>
<p>Menus you may not use are hidden. If you open such a page by its address anyway you get a "not allowed" message.</p>

<h2>Add an account</h2>
<ol>
    <li>Go to <em>Settings → Accounts</em>, fill in name, email and a password.</li>
    <li>Choose the role.</li>
    <li>For roles other than admin you can tick <strong>Only some routers</strong> and select which ones. Without it the account sees every router.</li>
    <li>Press <strong>Add account</strong> and give the person their password.</li>
</ol>

<h2>Change or remove an account</h2>
<p>In the list, change the role or the router selection and press <strong>Save</strong>, or press <strong>Remove</strong>. You cannot change your own role or delete your own account, so there is always an admin left.</p>
<p>Each person can change their own name, email and password from the account name at the bottom of the sidebar.</p>

<h2>Router limits</h2>
<p>An account limited to some routers sees only those routers in the sidebar, dashboard, reports and alerts. Other routers behave as if they do not exist. This suits an outlet cashier who should only see their own site.</p>

<h2>Audit log</h2>
<p><em>Manage → Audit log</em> (admins and technicians) records who did what and when: routers added, users and vouchers created, profiles changed, backups taken, settings and accounts changed, sessions disconnected, with the IP address. Use it to answer "who changed this?".</p>
